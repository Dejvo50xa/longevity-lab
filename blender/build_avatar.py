def asset(sub, name):
    f = glob.glob(os.path.join(data_dir(), sub, name, '*.mhclo'))
    return f'{name}/{os.path.basename(f[0])}' if f else None


def expression_target(name):
    """Full path of a caucasian expression unit (the same names exist for asian and african faces)."""
    root = os.path.join(bpy.utils.extension_path_user(ADDON, create=False).replace('/.user/', '/'), 'data', 'targets')
    hits = glob.glob(os.path.join(root, 'expression', 'units', 'caucasian', name + '.target.gz'))
    if not hits:  # fall back to the add-on's own data folder
        from bl_ext.user_default.mpfb.services.locationservice import LocationService
        hits = glob.glob(os.path.join(LocationService.get_mpfb_data('targets'), 'expression', 'units', 'caucasian', name + '.target.gz'))
    assert hits, f'expression target not found: {name}'
    return hits[0]


