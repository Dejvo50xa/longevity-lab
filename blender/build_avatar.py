def hair_of(sex, style):
    return STYLES[style].get('hair', {}).get(sex, LOOK[sex]['hair'])


def make_person(sex, style, variant):
    """Create one MakeHuman person; returns (rig, objects by part name)."""
    from bl_ext.user_default.mpfb.services.humanservice import HumanService
    from bl_ext.user_default.mpfb.services.targetservice import TargetService
    look, spec = LOOK[sex], VARIANTS.get(variant, {})
    hair = hair_of(sex, style)
    pheno = dict(BASE, gender=look['gender'], race={'caucasian': 1., 'asian': 0., 'african': 0.})
    pheno.update(spec.get('phenotype', {}))
    info = {
        'name': f'{sex}-{variant}', 'phenotype': pheno, 'rig': 'default',
        'eyes': asset('eyes', 'high-poly'), 'eyebrows': asset('eyebrows', look['eyebrows']),
        'eyelashes': asset('eyelashes', 'eyelashes01'), 'hair': asset('hair', hair),
        'clothes': [asset('clothes', c) for c in STYLES[style][sex]],
        'skin_mhmat': f'skins/{look["skin"]}/{look["skin"]}.mhmat',
        'skin_material_type': 'MAKESKIN', 'eyes_material_type': 'MAKESKIN', 'targets': [],
    }
    # Expression units must be on the body before eyebrows and lashes are fitted, so load them ourselves
    # right after the body is created (HumanService.create_human), by wrapping the target loader once.
    targets = spec.get('targets', {})
    original = HumanService._load_targets

    def load_with_expressions(human_info, basemesh):
        original(human_info, basemesh)
        for name, weight in targets.items():
            TargetService.load_target(basemesh, expression_target(name), weight=weight, name='expr-' + name)
    HumanService._load_targets = staticmethod(load_with_expressions)
    try:
        body = HumanService.deserialize_from_dict(info, HumanService.get_default_deserialization_settings())
    finally:
        HumanService._load_targets = staticmethod(original)
    rig = body.parent
    parts = {}
    for child in rig.children:
        if child.type != 'MESH':
            continue
        for m in child.modifiers:
            if m.type == 'SUBSURF':
                m.show_viewport = m.show_render = False
        suffix = child.name.split('.', 1)[1]
        key = PARTS.get(suffix)
        if key is None:
            key = 'hair' if suffix == hair else 'eyebrows' if suffix == look['eyebrows'] \
                else 'shoes' if suffix.startswith('shoes') else 'hat' if suffix.startswith('fedora') else 'clothes'
        parts[key] = child
    stand(rig, look.get('arm_out', .17))
    return rig, parts


# ---------------------------------------------------------------- posing helpers
def joint(rig, bone, tail=False):
    pb = rig.pose.bones[bone]
    return rig.matrix_world @ (pb.tail if tail else pb.head)


def rotate(rig, bone, axis, angle):
    """Rotate a pose bone (and its children) around a world-space axis through its head."""
    if abs(angle) < 1e-6:
        return
    a = joint(rig, bone)
    W = rig.matrix_world
    pb = rig.pose.bones[bone]
    R = Matrix.Translation(a) @ Matrix.Rotation(angle, 4, Vector(axis).normalized()) @ Matrix.Translation(-a)
    pb.matrix = W.inverted() @ R @ W @ pb.matrix
    bpy.context.view_layer.update()


def aim(rig, start, end, direction):
    bpy.context.view_layer.update()
    a, b = joint(rig, start), joint(rig, end)
    cur, d = (b - a).normalized(), Vector(direction).normalized()
    ang = cur.angle(d)
    axis = cur.cross(d)
    if ang < 1e-4 or axis.length < 1e-6:
        return
    rotate(rig, start, axis, ang)


def body_axes(rig):
    up = Vector((0, 0, 1))
    left = (joint(rig, 'upperleg01.L') - joint(rig, 'upperleg01.R')).normalized()
    fwd = up.cross(left).normalized()
    if (joint(rig, 'toe1-1.L') - joint(rig, 'foot.L')).dot(fwd) < 0:
        fwd = -fwd
    return up, left, fwd


def stand(rig, arm_out=.17):
    """Relaxed standing pose (from the sauna renders)."""
    up, left, fwd = body_axes(rig)
    for sd, s in ((1, '.L'), (-1, '.R')):
        aim(rig, 'upperleg01' + s, 'lowerleg01' + s, -up + left * sd * .03)
        aim(rig, 'lowerleg01' + s, 'foot' + s, -up)
        aim(rig, 'upperarm01' + s, 'lowerarm01' + s, -up + left * sd * arm_out + fwd * .03)
        aim(rig, 'lowerarm01' + s, 'wrist' + s, -up + fwd * .22 + left * sd * .05)


def hand_frame(rig, s):
    """(across, palm normal, finger direction) of one hand in world space; across points index -> pinky."""
    across = (joint(rig, 'finger5-1' + s) - joint(rig, 'finger2-1' + s)).normalized()
    fdir = (joint(rig, 'finger3-1' + s, tail=True) - joint(rig, 'finger3-1' + s)).normalized()
    # same handedness in every pose: with the arm hanging this points from the palm towards the thigh
    n = fdir.cross(across).normalized() * (1 if s == '.R' else -1)
    return across, n, fdir


def curl(rig, s, amounts, thumb=(0., 0.)):
    """Bend the fingers towards the palm. amounts: per finger 2..5 a (proximal, middle, distal) angle in degrees."""
    across, n, fdir = hand_frame(rig, s)
    for f, angles in zip((2, 3, 4, 5), amounts):
        for seg, deg in zip((1, 2, 3), angles):
            bone = f'finger{f}-{seg}{s}'
            d = (joint(rig, bone, tail=True) - joint(rig, bone)).normalized()
            axis = d.cross(n).normalized()  # rotating d around this by +angle moves it towards n
            rotate(rig, bone, axis, math.radians(deg))
    for seg, deg in zip((2, 3), thumb):
        bone = f'finger1-{seg}{s}'
        d = (joint(rig, bone, tail=True) - joint(rig, bone)).normalized()
        target = (joint(rig, 'finger3-2' + s) - joint(rig, bone)).normalized()  # thumb closes towards the middle finger
        axis = d.cross(target)
        if axis.length > 1e-5:
            rotate(rig, bone, axis, math.radians(deg))


