def frame(z, x):
    z = z.normalized()
    x = (x - z * x.dot(z)).normalized()
    return Matrix((x, z.cross(x), z)).transposed()


def reach(rig, s, local, target, direction, finger_dir, pole):
    """Put the hand so that a point fixed to the wrist lands on `target`, a wrist-fixed axis points along
    `direction` and the fingers point roughly along `finger_dir`; the elbow bends towards `pole`.
    local = (point, axis, fingers) in wrist space. Two-bone arm solved exactly, then the wrist is set."""
    point, axis, fingers = local
    W = rig.matrix_world
    R = frame(direction, finger_dir) @ frame(axis, fingers).transposed()
    wrist_world = R.to_4x4()
    wrist_world.translation = target - R @ point
    S = joint(rig, 'upperarm01' + s)
    E0 = joint(rig, 'lowerarm01' + s)
    L1, L2 = (E0 - S).length, (joint(rig, 'wrist' + s) - E0).length
    P = wrist_world.translation
    d = min((P - S).length, L1 + L2 - 1e-3)
    u = (P - S).normalized()
    a = (L1 * L1 - L2 * L2 + d * d) / (2 * d)
    h = math.sqrt(max(L1 * L1 - a * a, 0))
    pdir = (pole - u * pole.dot(u)).normalized()
    E = S + u * a + pdir * h
    aim(rig, 'upperarm01' + s, 'lowerarm01' + s, E - S)
    aim(rig, 'lowerarm01' + s, 'wrist' + s, S + u * d - joint(rig, 'lowerarm01' + s))
    # half of the forearm twist goes to the twist bone so the skin does not wrap like a sweet wrapper
    pb = rig.pose.bones['wrist' + s]
    pb.matrix = W.inverted() @ wrist_world
    bpy.context.view_layer.update()
    twist_bone = rig.pose.bones['lowerarm02' + s]
    fa = (joint(rig, 'wrist' + s) - joint(rig, 'lowerarm02' + s)).normalized()
    rel = (twist_bone.matrix.inverted() @ pb.matrix).to_quaternion()
    swing_axis_local = (twist_bone.matrix.to_3x3().inverted() @ (W.to_3x3().inverted() @ fa)).normalized()
    twist = rel.to_swing_twist('Y')[1] if hasattr(rel, 'to_swing_twist') else 0.
    if twist:
        keep = W.inverted() @ wrist_world
        rotate(rig, 'lowerarm02' + s, fa, twist * .5)
        pb.matrix = keep
        bpy.context.view_layer.update()
    M = W @ pb.matrix
    return (M @ point - target).length


# ---------------------------------------------------------------- baking variants into one mesh with shape keys
def world_coords(obj):
    """Final vertex positions (armature pose, masks, fitted clothes) in world space."""
    dg = bpy.context.evaluated_depsgraph_get()
    ev = obj.evaluated_get(dg)
    mesh = ev.to_mesh()
    M = obj.matrix_world
    co = [M @ v.co for v in mesh.vertices]
    ev.to_mesh_clear()
    return co


def bake_base(parts, coll):
    """Copy every part of the base person into a plain mesh object (keeps the bone weights, no modifiers)."""
    dg = bpy.context.evaluated_depsgraph_get()
    baked = {}
    for key, obj in parts.items():
        ev = obj.evaluated_get(dg)
        mesh = bpy.data.meshes.new_from_object(ev, preserve_all_data_layers=True, depsgraph=dg)
        mesh.transform(obj.matrix_world)
        new = bpy.data.objects.new(key, mesh)
        coll.objects.link(new)
        new.shape_key_add(name='Basis', from_mix=False)
        for poly in mesh.polygons:
            poly.use_smooth = True
        baked[key] = new
    return baked


def add_variant(baked, parts, name):
    for key, obj in parts.items():
        co = world_coords(obj)
        target = baked[key]
        assert len(co) == len(target.data.vertices), f'{name}/{key}: {len(co)} != {len(target.data.vertices)} vertices'
        kb = target.shape_key_add(name=name, from_mix=False)
        for i, c in enumerate(co):
            kb.data[i].co = c


def tuck_skin(baked, gap=.008, reach_=.03):
    """Keep the skin at least `gap` behind the clothes in every shape key.

    MakeHuman hides most skin under garments, but around waistbands and collars the skin can sit in front of
    tight fabric (more so at strong muscle/weight settings), which shows as skin patches on the web.
    """
    from mathutils.bvhtree import BVHTree
    body, cloth = baked['body'], baked.get('clothes')
    if cloth is None:
        return
    normals = [v.normal.copy() for v in body.data.vertices]
    polys = [tuple(p.vertices) for p in cloth.data.polygons]
    moved = 0
    for i, kb in enumerate(body.data.shape_keys.key_blocks):
        ck = cloth.data.shape_keys.key_blocks[kb.name]
        tree = BVHTree.FromPolygons([d.co for d in ck.data], polys)
        for vi, d in enumerate(kb.data):
            hit = tree.find_nearest(d.co, reach_)
            # only skin the garment actually covers: fabric facing the same way as the skin
            # (fingers resting against a thigh face the fabric, so they are left alone)
            if hit[0] is None or hit[1].dot(normals[vi]) < .3:
                continue
            ahead = (hit[0] - d.co).dot(normals[vi])  # how far the fabric is in front of the skin
            if ahead < gap:
                d.co -= normals[vi] * (gap - ahead)
                moved += i == 0
    print(f'TUCK moved {moved} skin vertices behind the clothes')


def tuck_hair(baked, center, gap=.004):
    """MakeHuman does not squash hair under a hat: pull every hair vertex that pokes out of the hat back inside it
    (ray from the middle of the head to the vertex), in every shape key."""
    from mathutils.bvhtree import BVHTree
    hat, hair = baked.get('hat'), baked.get('hair')
    if hat is None or hair is None:
        return
    polys = [tuple(p.vertices) for p in hat.data.polygons]
    moved = 0
    for i, kb in enumerate(hair.data.shape_keys.key_blocks):
        hk = hat.data.shape_keys.key_blocks[kb.name]
        tree = BVHTree.FromPolygons([d.co for d in hk.data], polys)
        for d in kb.data:
            ray = d.co - center
            dist = ray.length
            hit = tree.ray_cast(center, ray.normalized(), dist)
            if hit[0] is not None:
                d.co = hit[0] - ray.normalized() * gap
                moved += i == 0
    print(f'TUCK moved {moved} hair vertices under the hat')


