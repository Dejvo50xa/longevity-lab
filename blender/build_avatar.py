def preview(coll, rig, sex, style, shapes):
    os.makedirs(PREVIEWS, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = 'BLENDER_EEVEE'
    scene.render.film_transparent = False
    scene.world = scene.world or bpy.data.worlds.new('w')
    scene.world.color = (.85, .88, .92)
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam'))
    scene.collection.objects.link(cam)
    scene.camera = cam
    body = coll.objects['body']
    top = max((body.matrix_world @ v.co).z for v in body.data.vertices)
    for i, (loc, energy) in enumerate((((-2, -3, 3), 500), ((3, -2, 2.5), 250), ((0, 3, 3), 400))):
        light = bpy.data.objects.new(f'l{i}', bpy.data.lights.new(f'l{i}', 'AREA'))
        light.data.energy, light.data.size = energy, 3
        light.location = loc
        light.rotation_euler = (Vector((0, 0, 1)) - Vector(loc)).to_track_quat('-Z', 'Y').to_euler()
        scene.collection.objects.link(light)
    hr = joint(rig, 'finger3-1.R')
    shots = {'hand': (70, hr + Vector((-.35, -.45, .12)), hr, (600, 600)),
             'full': (50, Vector((-.6, -4.2, top * .55)), Vector((0, 0, top * .52)), (700, 1100)),
             'face': (60, Vector((-.25, -1.4, top * .9)), Vector((0, 0, top * .86)), (700, 700))}
    tracks = rig.animation_data.nla_tracks

    def set_keys(name):
        for o in coll.objects:
            if o.type == 'MESH' and o.data.shape_keys:
                for kb in o.data.shape_keys.key_blocks:
                    kb.value = 1. if kb.name == name else 0.

    def shoot(tag, which=('full', 'face')):
        for shot in which:
            lens, loc, target, res = shots[shot]
            cam.data.lens = lens
            cam.location = loc
            cam.rotation_euler = (target - loc).to_track_quat('-Z', 'Y').to_euler()
            scene.render.resolution_x, scene.render.resolution_y = res
            scene.render.filepath = os.path.join(PREVIEWS, f'{sex}-{style}-{shot}-{tag}.png')
            bpy.ops.render.render(write_still=True)

    def show(names):
        for o in coll.objects:
            if o.name.startswith('prop_'):
                o.hide_render = o.name[5:] not in names

    for frame, label, live in ((1, 'hold', ('smoke', 'drink')), (25, 'smoke', ('smoke',)), (25, 'drink', ('drink',))):
        for t in tracks:
            t.mute = t.name not in live
        scene.frame_set(frame)
        show({'cigarette', 'beer'})
        shoot(f'a-{label}', ('full', 'face', 'hand') if label != 'drink' else ('face',))
        show({'cigar', 'whisky'} if style == 'gangster' else {'vape', 'wine'})
        shoot(f'b-{label}', ('full',) if label == 'hold' else ('face',))
    for t in tracks:
        t.mute = True
    scene.frame_set(1)
    show(set())
    for name in ['Basis'] + shapes:
        set_keys(name)
        shoot(name, ('full',))
    set_keys('Basis')


def build(sex, style, want_preview, quick):
    clear_scene()
    coll = bpy.data.collections.new(f'avatar-{sex}-{style}')
    bpy.context.scene.collection.children.link(coll)
    rig, parts = make_person(sex, style, 'base')
    baked = bake_base(parts, coll)
    for key, obj in baked.items():
        for mat in obj.data.materials:
            mat.use_fake_user = True  # MPFB deletes unused materials while building the variants
    remove_person(rig, keep_rig=True)
    # the standing pose becomes the rest pose of the kept skeleton
    bpy.context.view_layer.objects.active = rig
    bpy.ops.object.mode_set(mode='POSE')
    bpy.ops.pose.select_all(action='SELECT')
    bpy.ops.pose.armature_apply(selected=False)
    bpy.ops.object.mode_set(mode='OBJECT')
    rig.name = rig.data.name = 'skeleton'
    coll.objects.link(rig)
    for c in list(rig.users_collection):
        if c != coll:
            c.objects.unlink(rig)
    shapes = [] if quick else list(VARIANTS)
    for name in shapes:
        r, p = make_person(sex, style, name)
        add_variant(baked, p, name)
        remove_person(r)
        print(f'VARIANT {sex}/{style}/{name} ok')
    tuck_skin(baked)
    tuck_hair(baked, (joint(rig, 'head') * .4 + joint(rig, 'head', tail=True) * .6))
    recol = STYLES[style].get('recolor', {}).get(sex)
    for key, obj in baked.items():
        for mat in obj.data.materials:
            simplify_material(mat, key, LOOK[sex], recol)
        obj.parent = rig
        mod = obj.modifiers.new('skeleton', 'ARMATURE')
        mod.object = rig
        print(f'PART {key}: {len(obj.data.vertices)} vertices, {len(obj.data.shape_keys.key_blocks) - 1} shape keys')
    props = make_props()
    for obj in baked.values():  # posing is much faster without deforming the meshes
        obj.modifiers['skeleton'].show_viewport = False
    smoke_and_drink(rig, sex, props, coll)
    for obj in baked.values():
        obj.modifiers['skeleton'].show_viewport = True
    export(coll, sex, style)
    if want_preview:
        preview(coll, rig, sex, style, shapes)


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    addon_utils.enable(ADDON, default_set=True)
    sexes = [argv[argv.index('--sex') + 1]] if '--sex' in argv else ['male', 'female']
    styles = [argv[argv.index('--style') + 1]] if '--style' in argv else list(STYLES)
    for sex in sexes:
        for style in styles:
            build(sex, style, '--preview' in argv, '--quick' in argv)


main()
