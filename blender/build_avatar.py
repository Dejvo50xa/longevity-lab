"""Build the 3D avatar for the calculator: one realistic MakeHuman person per sex, exported as a GLB with morph targets.

Run (Blender 5.x with the free MPFB extension installed, same setup as ~/dev/longevityclinic/blender):

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -P blender/build_avatar.py
    ... -- --sex male          # only one figure
    ... -- --preview           # also render preview PNGs to blender/previews/ (not committed)

How it works: MakeHuman cannot change body shape smoothly on the web, so every look the calculator needs
(muscular, heavier, thinner, older, smiling, sad, tired) is built as a separate MakeHuman person with the
same assets. Each one is posed the same way, and its final vertex positions become a shape key (glTF morph
target) on the base person. On the web, three.js blends these keys with the calculator's inputs.

Everything generated by MakeHuman is CC0. Clothes and hair below come from the MakeHuman system assets (CC0).
"""
import glob
import math
import os
import re
import sys

import addon_utils
import bpy
from mathutils import Matrix, Vector

ADDON = 'bl_ext.user_default.mpfb'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'public', 'models')
PREVIEWS = os.path.join(HERE, 'previews')

# Base person: an average 25-year-old. Variants change one thing each; the web blends them.
BASE = {'age': .5, 'muscle': .5, 'weight': .5, 'height': .5, 'proportions': .5, 'cupsize': .5, 'firmness': .5}
VARIANTS = {
    'muscle': {'phenotype': {'muscle': 1.}},
    'soft': {'phenotype': {'muscle': .05}},
    'heavy': {'phenotype': {'weight': 1.}},
    'thin': {'phenotype': {'weight': 0.}},
    'old': {'phenotype': {'age': .92}},  # MakeHuman age 0.5 = 25 years, 1.0 = 90 years -> 0.92 is about 80
    'smile': {'targets': {'mouth-corner-puller': 1., 'mouth-elevation': .25, 'eye-left-slit': .25, 'eye-right-slit': .25}},
    'sad': {'targets': {'mouth-depression': .9, 'eyebrows-left-inner-up': .8, 'eyebrows-right-inner-up': .8}},
    'tired': {'targets': {'eye-left-closure': .55, 'eye-right-closure': .55, 'eyebrows-left-down': .4, 'eyebrows-right-down': .4}},
}
LOOK = {
    # Sportswear so that muscle and weight changes stay visible (jeans and a loose T-shirt hid them).
    'male': {'gender': 1., 'skin': 'young_caucasian_male', 'hair': 'short02', 'eyebrows': 'eyebrow001', 'eyes': 'bluegreen',
             'clothes': ['mindfront_male_swimming_trunks_01', 'shoes05']},  # shorts: Mindfront, CC BY 4.0
    'female': {'gender': 0., 'skin': 'young_caucasian_female', 'hair': 'ponytail01', 'eyebrows': 'eyebrow010', 'eyes': 'brownlight', 'arm_out': .26,  # wider hips: keep the hands off the thighs
               'clothes': ['female_sportsuit01', 'shoes05']},
}
PARTS = {  # MakeHuman object name suffix -> name in the GLB (the web code looks these up)
    'body': 'body', 'high-poly': 'eyes', 'eyelashes01': 'eyelashes',
}
TEXTURE_SIZE = {'body': 2048}  # everything else is scaled to 1024


def data_dir():
    return os.path.join(bpy.utils.extension_path_user(ADDON, create=True), 'data')


def asset(sub, name):
    f = glob.glob(os.path.join(data_dir(), sub, name, '*.mhclo'))
    return f'{name}/{os.path.basename(f[0])}' if f else None


def expression_target(name):
    """Full path of a caucasian expression unit (the same names exist for asian and african faces)."""
    root = os.path.join(bpy.utils.extension_path_user(ADDON, create=False).replace('/.user/', '/'), 'data', 'targets')
    hits = glob.glob(os.path.join(root, 'expression', 'units', 'caucasian', name + '.target.gz'))
    if not hits:  # fall back to the add-on's own data folder
        from bl_ext.user_default.mpfb.services.locationservice import LocationService
        hits = glob.glob(os.path.join(LocationService.get_mpfb_data('targets'), 'expression', 'units', 'caucasian', name + '.target.gz'))
    assert hits, f'expression target not found: {name}'
    return hits[0]


def clear_scene():
    for o in list(bpy.data.objects):
        bpy.data.objects.remove(o, do_unlink=True)


def make_person(sex, variant):
    """Create one MakeHuman person for this sex and variant; returns (rig, objects by part name)."""
    from bl_ext.user_default.mpfb.services.humanservice import HumanService
    from bl_ext.user_default.mpfb.services.targetservice import TargetService
    look, spec = LOOK[sex], VARIANTS.get(variant, {})
    pheno = dict(BASE, gender=look['gender'], race={'caucasian': 1., 'asian': 0., 'african': 0.})
    pheno.update(spec.get('phenotype', {}))
    info = {
        'name': f'{sex}-{variant}', 'phenotype': pheno, 'rig': 'default',
        'eyes': asset('eyes', 'high-poly'), 'eyebrows': asset('eyebrows', look['eyebrows']),
        'eyelashes': asset('eyelashes', 'eyelashes01'), 'hair': asset('hair', look['hair']),
        'clothes': [asset('clothes', c) for c in look['clothes']],
        'skin_mhmat': f'skins/{look["skin"]}/{look["skin"]}.mhmat',
        'skin_material_type': 'MAKESKIN', 'eyes_material_type': 'MAKESKIN', 'targets': [],
    }
    # Expression units must be on the body before eyebrows and lashes are fitted, so load them ourselves
    # right after the body is created (HumanService.create_human), by wrapping the target loader once.
    targets = spec.get('targets', {})
    original = HumanService._load_targets

    def load_with_expressions(human_info, basemesh):
        original(human_info, basemesh)
        for name, weight in targets.items():
            TargetService.load_target(basemesh, expression_target(name), weight=weight, name='expr-' + name)
    HumanService._load_targets = staticmethod(load_with_expressions)
    try:
        body = HumanService.deserialize_from_dict(info, HumanService.get_default_deserialization_settings())
    finally:
        HumanService._load_targets = staticmethod(original)
    rig = body.parent
    parts = {}
    for child in rig.children:
        if child.type != 'MESH':
            continue
        for m in child.modifiers:
            if m.type == 'SUBSURF':
                m.show_viewport = m.show_render = False
        suffix = child.name.split('.', 1)[1]
        key = PARTS.get(suffix)
        if key is None:
            key = 'hair' if suffix == look['hair'] else 'eyebrows' if suffix == look['eyebrows'] \
                else 'shoes' if suffix.startswith('shoes') else 'clothes'
        parts[key] = child
    stand(rig, look.get('arm_out', .17))
    return rig, parts


# ---------------------------------------------------------------- relaxed standing pose (from the sauna renders)
def joint(rig, bone):
    return rig.matrix_world @ rig.pose.bones[bone].head


def aim(rig, start, end, direction):
    bpy.context.view_layer.update()
    a, b = joint(rig, start), joint(rig, end)
    cur, d = (b - a).normalized(), Vector(direction).normalized()
    ang = cur.angle(d)
    axis = cur.cross(d)
    if ang < 1e-4 or axis.length < 1e-6:
        return
    W = rig.matrix_world
    pb = rig.pose.bones[start]
    R = Matrix.Translation(a) @ Matrix.Rotation(ang, 4, axis.normalized()) @ Matrix.Translation(-a)
    pb.matrix = W.inverted() @ R @ W @ pb.matrix
    bpy.context.view_layer.update()


def stand(rig, arm_out=.17):
    up = Vector((0, 0, 1))
    left = (joint(rig, 'upperleg01.L') - joint(rig, 'upperleg01.R')).normalized()
    fwd = up.cross(left).normalized()
    if (joint(rig, 'toe1-1.L') - joint(rig, 'foot.L')).dot(fwd) < 0:
        fwd = -fwd
    for sd, s in ((1, '.L'), (-1, '.R')):
        aim(rig, 'upperleg01' + s, 'lowerleg01' + s, -up + left * sd * .03)
        aim(rig, 'lowerleg01' + s, 'foot' + s, -up)
        aim(rig, 'upperarm01' + s, 'lowerarm01' + s, -up + left * sd * arm_out + fwd * .03)
        aim(rig, 'lowerarm01' + s, 'wrist' + s, -up + fwd * .22 + left * sd * .05)


# ---------------------------------------------------------------- baking variants into one mesh with shape keys
def world_coords(obj):
    """Final vertex positions (armature pose, masks, fitted clothes) in world space."""
    dg = bpy.context.evaluated_depsgraph_get()
    ev = obj.evaluated_get(dg)
    mesh = ev.to_mesh()
    M = obj.matrix_world
    co = [M @ v.co for v in mesh.vertices]
    ev.to_mesh_clear()
    return co


def bake_base(parts, coll):
    """Copy every part of the base person into a plain mesh object (no rig, no modifiers)."""
    dg = bpy.context.evaluated_depsgraph_get()
    baked = {}
    for key, obj in parts.items():
        ev = obj.evaluated_get(dg)
        mesh = bpy.data.meshes.new_from_object(ev, preserve_all_data_layers=True, depsgraph=dg)
        mesh.transform(obj.matrix_world)
        if mesh.shape_keys:  # new_from_object can carry the MakeHuman macro keys; the result already includes them
            pass
        new = bpy.data.objects.new(key, mesh)
        coll.objects.link(new)
        new.shape_key_add(name='Basis', from_mix=False)
        for poly in mesh.polygons:
            poly.use_smooth = True
        baked[key] = new
    return baked


def add_variant(baked, parts, name):
    for key, obj in parts.items():
        co = world_coords(obj)
        target = baked[key]
        assert len(co) == len(target.data.vertices), f'{name}/{key}: {len(co)} != {len(target.data.vertices)} vertices'
        kb = target.shape_key_add(name=name, from_mix=False)
        for i, c in enumerate(co):
            kb.data[i].co = c


def tuck_skin(baked, gap=.008, reach=.03):
    """Keep the skin at least `gap` behind the clothes in every shape key.

    MakeHuman hides most skin under garments, but around waistbands the skin can sit in front of tight
    fabric (and does so more at strong muscle/weight settings), which shows as skin patches on the web.
    """
    from mathutils.bvhtree import BVHTree
    body, cloth = baked['body'], baked.get('clothes')
    if cloth is None:
        return
    normals = [v.normal.copy() for v in body.data.vertices]
    polys = [tuple(p.vertices) for p in cloth.data.polygons]
    moved = 0
    for i, kb in enumerate(body.data.shape_keys.key_blocks):
        ck = cloth.data.shape_keys.key_blocks[kb.name]
        tree = BVHTree.FromPolygons([d.co for d in ck.data], polys)
        for vi, d in enumerate(kb.data):
            hit = tree.find_nearest(d.co, reach)
            # only skin the garment actually covers: fabric facing the same way as the skin
            # (fingers resting against a thigh face the fabric, so they are left alone)
            if hit[0] is None or hit[1].dot(normals[vi]) < .3:
                continue
            ahead = (hit[0] - d.co).dot(normals[vi])  # how far the fabric is in front of the skin
            if ahead < gap:
                d.co -= normals[vi] * (gap - ahead)
                moved += i == 0
    print(f'TUCK moved {moved} skin vertices behind the clothes')


def remove_person(rig):
    for child in list(rig.children):
        bpy.data.objects.remove(child, do_unlink=True)
    bpy.data.objects.remove(rig, do_unlink=True)


# ---------------------------------------------------------------- materials the glTF exporter understands
def simplify_material(mat, key, look):
    """Base colour texture straight into the BSDF (MakeHuman mixes in AO/colour nodes glTF cannot export)."""
    nt = mat.node_tree
    bsdf = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
    images = [n for n in nt.nodes if n.type == 'TEX_IMAGE' and n.image]
    kind = lambda n: n.image.name.lower()
    # MakeHuman names maps inconsistently: *_normal.png, *_NRM.png, *_SPEC.png, *_ao.png
    diffuse = next((n for n in images if not re.search(r'normal|nrm|spec|_ao|bump', kind(n))), None)
    normal = next((n for n in images if re.search(r'normal|nrm', kind(n))), None)
    for n in list(nt.nodes):
        if n not in (bsdf, diffuse, normal) and n.type not in ('OUTPUT_MATERIAL',):
            nt.nodes.remove(n)
    if diffuse and key == 'eyes':  # MakeHuman's default 'brown' iris reads as red on screen
        path = os.path.join(data_dir(), 'eyes', 'materials', look['eyes'] + '_eye.png')
        diffuse.image = bpy.data.images.load(path, check_existing=True)
    if diffuse:
        nt.links.new(diffuse.outputs['Color'], bsdf.inputs['Base Color'])
        for link in list(bsdf.inputs['Alpha'].links):
            nt.links.remove(link)
        bsdf.inputs['Alpha'].default_value = 1.
        if key in ('hair', 'eyebrows', 'eyelashes', 'eyes'):  # cut-outs; eyes: the cornea shell is see-through
            nt.links.new(diffuse.outputs['Alpha'], bsdf.inputs['Alpha'])
            mat.surface_render_method = 'DITHERED'
        else:  # skin, clothes and shoes are opaque (MakeHuman marks them transparent, glTF would blend them)
            mat.surface_render_method = 'DITHERED'
            if hasattr(mat, 'blend_method'):
                mat.blend_method = 'OPAQUE'
        size = TEXTURE_SIZE.get(key, 1024)
        if diffuse.image.size[0] > size:
            diffuse.image.scale(size, size)
    if normal:
        nm = nt.nodes.new('ShaderNodeNormalMap')
        normal.image.colorspace_settings.name = 'Non-Color'
        nt.links.new(normal.outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
        if normal.image.size[0] > 1024:
            normal.image.scale(1024, 1024)
    bsdf.inputs['Roughness'].default_value = {'body': .55, 'eyes': .15, 'clothes': .8}.get(key, .6)
    if 'Specular IOR Level' in bsdf.inputs:
        bsdf.inputs['Specular IOR Level'].default_value = .35 if key == 'body' else .5
    mat.name = key


# ---------------------------------------------------------------- export and preview
def anchors(rig, coll):
    """Empties the web code uses to attach a cigarette, a glass and sauna steam."""
    for name, bone in (('anchor_hand_R', 'wrist.R'), ('anchor_hand_L', 'wrist.L'), ('anchor_head', 'head')):
        pb = rig.pose.bones[bone]
        e = bpy.data.objects.new(name, None)
        e.location = rig.matrix_world @ (pb.tail if bone != 'head' else pb.tail)
        coll.objects.link(e)


def export(coll, sex):
    os.makedirs(OUT, exist_ok=True)
    bpy.ops.object.select_all(action='DESELECT')
    for o in coll.objects:
        o.select_set(True)
    path = os.path.abspath(os.path.join(OUT, f'avatar-{sex}.glb'))
    bpy.ops.export_scene.gltf(
        filepath=path, export_format='GLB', use_selection=True, export_apply=False,
        export_morph=True, export_morph_normal=True, export_morph_tangent=False,
        export_skins=False, export_animations=False, export_materials='EXPORT',
        export_image_format='WEBP', export_image_quality=82,
        export_draco_mesh_compression_enable=True, export_draco_mesh_compression_level=7,
        export_draco_position_quantization=14, export_draco_normal_quantization=10, export_draco_texcoord_quantization=12,
        export_extras=False, export_yup=True)
    print(f'EXPORTED {path} {os.path.getsize(path) / 1e6:.2f} MB')


def preview(coll, sex):
    os.makedirs(PREVIEWS, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = 'BLENDER_EEVEE'
    scene.render.film_transparent = False
    scene.world = scene.world or bpy.data.worlds.new('w')
    scene.world.color = (.85, .88, .92)
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam'))
    scene.collection.objects.link(cam)
    scene.camera = cam
    body = coll.objects['body']
    top = max((body.matrix_world @ v.co).z for v in body.data.vertices)
    for i, (loc, energy) in enumerate((((-2, -3, 3), 500), ((3, -2, 2.5), 250), ((0, 3, 3), 400))):
        light = bpy.data.objects.new(f'l{i}', bpy.data.lights.new(f'l{i}', 'AREA'))
        light.data.energy, light.data.size = energy, 3
        light.location = loc
        light.rotation_euler = (Vector((0, 0, 1)) - Vector(loc)).to_track_quat('-Z', 'Y').to_euler()
        scene.collection.objects.link(light)
    shots = {'full': (50, Vector((0, -4.2, top * .55)), Vector((0, 0, top * .52)), (700, 1100)),
             'face': (85, Vector((0, -.9, top * .94)), Vector((0, 0, top * .935)), (600, 600))}
    for name in ['Basis'] + list(VARIANTS):
        for o in coll.objects:
            if o.type == 'MESH' and o.data.shape_keys:
                for kb in o.data.shape_keys.key_blocks:
                    kb.value = 1. if kb.name == name else 0.
        for shot, (lens, loc, target, res) in shots.items():
            cam.data.lens = lens
            cam.location = loc
            cam.rotation_euler = (target - loc).to_track_quat('-Z', 'Y').to_euler()
            scene.render.resolution_x, scene.render.resolution_y = res
            scene.render.filepath = os.path.join(PREVIEWS, f'{sex}-{shot}-{name}.png')
            bpy.ops.render.render(write_still=True)
    for o in coll.objects:
        if o.type == 'MESH' and o.data.shape_keys:
            for kb in o.data.shape_keys.key_blocks:
                kb.value = 0.


def build(sex, want_preview):
    clear_scene()
    coll = bpy.data.collections.new(f'avatar-{sex}')
    bpy.context.scene.collection.children.link(coll)
    rig, parts = make_person(sex, 'base')
    baked = bake_base(parts, coll)
    anchors(rig, coll)
    for key, obj in baked.items():
        for mat in obj.data.materials:
            mat.use_fake_user = True  # MPFB deletes unused materials while building the variants
    remove_person(rig)
    for name in VARIANTS:
        r, p = make_person(sex, name)
        add_variant(baked, p, name)
        remove_person(r)
        print(f'VARIANT {sex}/{name} ok')
    tuck_skin(baked)
    for key, obj in baked.items():
        for mat in obj.data.materials:
            simplify_material(mat, key, LOOK[sex])
        print(f'PART {key}: {len(obj.data.vertices)} vertices, {len(obj.data.shape_keys.key_blocks) - 1} shape keys')
    export(coll, sex)
    if want_preview:
        preview(coll, sex)


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    addon_utils.enable(ADDON, default_set=True)
    sexes = [argv[argv.index('--sex') + 1]] if '--sex' in argv else ['male', 'female']
    for sex in sexes:
        build(sex, '--preview' in argv)


main()
