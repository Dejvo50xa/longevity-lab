"""Build the 3D avatars for the calculator: one realistic MakeHuman person per sex and clothing style, each
exported as a GLB with morph targets, a skeleton, hand-held props and two short arm animations.

Run (Blender 5.x with the free MPFB extension installed, same setup as ~/dev/longevityclinic/blender):

    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -P blender/build_avatar.py
    ... -- --sex male --style lawyer   # only some figures
    ... -- --preview                   # also render preview PNGs to blender/previews/ (not committed)
    ... -- --quick                     # skip the body variants (fast look at clothes, props and poses)

How it works: MakeHuman cannot change body shape smoothly on the web, so every look the calculator needs
(muscular, heavier, thinner, older, smiling, sad, tired) is built as a separate MakeHuman person with the
same assets. Each one is posed the same way, and its final vertex positions become a shape key (glTF morph
target) on the base person. On the web, three.js blends these keys with the calculator's inputs.

The base person keeps its skeleton (standing pose = rest pose), so the web can raise the right hand to the
mouth (animation "smoke") and hold a drink in the left hand (animation "drink"). The props (cigarette, cigar,
e-cigarette, beer can, wine glass, whisky tumbler, shot glass) are modelled here and parented to hand bones.

Everything generated by MakeHuman is CC0; asset licences are listed in public/models/CREDITS.md.
"""
