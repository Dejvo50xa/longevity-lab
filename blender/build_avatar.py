# ---------------------------------------------------------------- materials the glTF exporter understands
def recolor(image, mode):
    """Restyle the elegant suit texture: 'navy' (lawyer) or 'pinstripe' (dark suit, dark shirt, red tie)."""
    w, h = image.size
    px = np.empty(w * h * 4, dtype=np.float32)
    image.pixels.foreach_get(px)
    px = px.reshape(h, w, 4)
    rgb = px[..., :3]
    mx, mn = rgb.max(-1), rgb.min(-1)
    sat = (mx - mn) / np.maximum(mx, 1e-4)
    lum = rgb @ np.array([.3, .59, .11], dtype=np.float32)
    if mode == 'dark':  # charcoal felt hat
        rgb *= .45
    if mode == 'tights':  # white sports socks -> dark sheer tights
        sock = (sat < .15) & (mx > .5)
        rgb[sock] = lum[sock, None] * np.array([.2, .17, .16], dtype=np.float32)
    fabric = (sat < .12) & (mx < .45)     # the charcoal cloth of jacket and trousers
    shirt = (sat < .12) & (mx > .6)       # white shirt and the white stripes of the tie
    tie = sat > .22                       # blue tie
    if mode == 'navy':
        rgb[fabric] = lum[fabric, None] * np.array([.62, .78, 1.45], dtype=np.float32)
    elif mode == 'pinstripe':
        x = np.arange(w)[None, :].repeat(h, 0)
        stripe = (x % max(w // 64, 6)) < max(w // 700, 1)  # thin vertical chalk lines
        base = lum[..., None] * np.array([.42, .42, .46], dtype=np.float32)
        rgb[fabric] = base[fabric]
        rgb[fabric & stripe] = np.clip(base[fabric & stripe] + .17, 0, 1)
        rgb[shirt] = lum[shirt, None] * np.array([.16, .16, .18], dtype=np.float32)
        rgb[tie] = lum[tie, None] * np.array([1.5, .22, .2], dtype=np.float32)
    px[..., :3] = rgb
    image.pixels.foreach_set(px.ravel())
    image.update()


def simplify_material(mat, key, look, style_recolor=None):
    """Base colour texture straight into the BSDF (MakeHuman mixes in AO/colour nodes glTF cannot export)."""
    nt = mat.node_tree
    bsdf = next(n for n in nt.nodes if n.type == 'BSDF_PRINCIPLED')
    images = [n for n in nt.nodes if n.type == 'TEX_IMAGE' and n.image]
    kind = lambda n: n.image.name.lower()
    # MakeHuman names maps inconsistently: *_normal.png, *_NRM.png, *_SPEC.png, *_ao.png
    diffuse = next((n for n in images if not re.search(r'normal|nrm|spec|_ao|bump', kind(n))), None)
    normal = next((n for n in images if re.search(r'normal|nrm', kind(n))), None)
    for n in list(nt.nodes):
        if n not in (bsdf, diffuse, normal) and n.type not in ('OUTPUT_MATERIAL',):
            nt.nodes.remove(n)
    if diffuse and key == 'eyes':  # MakeHuman's default 'brown' iris reads as red on screen
        path = os.path.join(data_dir(), 'eyes', 'materials', look['eyes'] + '_eye.png')
        diffuse.image = bpy.data.images.load(path, check_existing=True)
    if diffuse:
        nt.links.new(diffuse.outputs['Color'], bsdf.inputs['Base Color'])
        for link in list(bsdf.inputs['Alpha'].links):
            nt.links.remove(link)
        bsdf.inputs['Alpha'].default_value = 1.
        if key in ('hair', 'eyebrows', 'eyelashes', 'eyes'):  # cut-outs; eyes: the cornea shell is see-through
            nt.links.new(diffuse.outputs['Alpha'], bsdf.inputs['Alpha'])
            mat.surface_render_method = 'DITHERED'
        else:  # skin, clothes and shoes are opaque (MakeHuman marks them transparent, glTF would blend them)
            mat.surface_render_method = 'DITHERED'
            if hasattr(mat, 'blend_method'):
                mat.blend_method = 'OPAQUE'
        size = TEXTURE_SIZE.get(key, 1024)
        if diffuse.image.size[0] > size:
            diffuse.image.scale(size, size)
        if style_recolor and key in style_recolor:
            diffuse.image = diffuse.image.copy()  # never touch the shared MakeHuman file
            recolor(diffuse.image, style_recolor[key])
    if normal:
        nm = nt.nodes.new('ShaderNodeNormalMap')
        normal.image.colorspace_settings.name = 'Non-Color'
        nt.links.new(normal.outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
        if normal.image.size[0] > 1024:
            normal.image.scale(1024, 1024)
    bsdf.inputs['Roughness'].default_value = {'body': .55, 'eyes': .15, 'clothes': .8, 'hat': .85}.get(key, .6)
    if 'Specular IOR Level' in bsdf.inputs:
        bsdf.inputs['Specular IOR Level'].default_value = .35 if key == 'body' else .5
    mat.name = key


# ---------------------------------------------------------------- props
def material(name, color, rough=.5, metal=0., emit=None):
    m = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    m.use_nodes = True
    b = next(n for n in m.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    b.inputs['Base Color'].default_value = (*color, 1)
    b.inputs['Roughness'].default_value = rough
    b.inputs['Metallic'].default_value = metal
    if emit:
        b.inputs['Emission Color'].default_value = (*emit, 1)
        b.inputs['Emission Strength'].default_value = 1.
    return m


def lathe(name, profile, mat, segments=32, cap_top=False, cap_bottom=True):
    """Solid of revolution around +Z from a list of (radius, height) points (metres)."""
    bm = bmesh.new()
    rings = []
    for r, z in profile:
        ring = [bm.verts.new((r * math.cos(2 * math.pi * i / segments), r * math.sin(2 * math.pi * i / segments), z)) for i in range(segments)]
        rings.append(ring)
    for a, b in zip(rings, rings[1:]):
        for i in range(segments):
            j = (i + 1) % segments
            bm.faces.new((a[i], a[j], b[j], b[i]))
    if cap_bottom and profile[0][0] > 1e-5:
        bm.faces.new(list(reversed(rings[0])))
    if cap_top and profile[-1][0] > 1e-5:
        bm.faces.new(rings[-1])
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    for p in me.polygons:
        p.use_smooth = True
    me.materials.append(mat)
    o = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(o)
    return o


def box(name, size, mat, z0=0.):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.)
    for v in bm.verts:
        v.co = Vector((v.co.x * size[0], v.co.y * size[1], v.co.z * size[2] + z0 + size[2] / 2))
    bmesh.ops.bevel(bm, geom=list(bm.edges), offset=min(size) * .18, segments=2, affect='EDGES')
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(mat)
    o = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(o)
    return o


def join(name, objs):
    for o in bpy.context.selected_objects:
        o.select_set(False)
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    bpy.ops.object.join()
    o = objs[0]
    o.name = o.data.name = name
    return o


def empty(name, loc, parent):
    e = bpy.data.objects.new(name, None)
    bpy.context.scene.collection.objects.link(e)
    e.parent = parent
    e.location = loc
    return e


def cyl(r, z0, z1):
    return [(r, z0), (r, z1)]


