# ---------------------------------------------------------------- hand poses, prop placement and animations
def place(obj, origin, zdir, xhint):
    """World matrix for a prop: its +Z along zdir, its origin at `origin`."""
    z = zdir.normalized()
    x = (xhint - z * xhint.dot(z)).normalized()
    y = z.cross(x)
    M = Matrix((x, y, z)).transposed().to_4x4()
    M.translation = origin
    obj.matrix_world = M
    return M


def key_pose(rig, s, frame):
    for b in ARM:
        pb = rig.pose.bones.get(b + s)
        if pb:
            pb.rotation_mode = 'QUATERNION'
            pb.keyframe_insert('rotation_quaternion', frame=frame, group=pb.name)


def to_track(rig, name):
    ad = rig.animation_data
    act = ad.action
    act.name = name
    track = ad.nla_tracks.new()
    track.name = name
    track.strips.new(name, int(act.frame_range[0]), act)
    ad.action = None
    for pb in rig.pose.bones:
        pb.matrix_basis = Matrix()
    bpy.context.view_layer.update()


def pose_bone_world(rig, bone):
    return rig.matrix_world @ rig.pose.bones[bone].matrix


def attach(rig, obj, bone, world_in_pose):
    """Parent obj to a bone so that it sits at `world_in_pose` while the rig is in the current (posed) state."""
    rel = pose_bone_world(rig, bone).inverted() @ world_in_pose
    obj['rel'] = [list(r) for r in rel]
    obj['bone'] = bone


def finish_attach(rig, objs):
    """Call with the rig back in rest pose: parent each prop keeping its bone-relative transform."""
    bpy.context.view_layer.update()
    for o in objs:
        rel = Matrix(o['rel'])
        bone = o['bone']
        o.parent = rig
        o.parent_type = 'BONE'
        o.parent_bone = bone
        bpy.context.view_layer.update()
        o.matrix_world = pose_bone_world(rig, bone) @ rel
        del o['rel'], o['bone']


def smoke_and_drink(rig, sex, props, coll):
    """Right hand: hold a cigarette (frame 1) and bring it to the lips (frame 25) -> track 'smoke'.
    Left hand: hold a drink in front of the hip (frame 1) and take a sip (frame 25) -> track 'drink'."""
    up, left, fwd = body_axes(rig)
    lips = (joint(rig, 'oris01', tail=True) + joint(rig, 'oris05')) / 2
    rig.animation_data_create()
    placed = []
    for pb in rig.pose.bones:
        pb.rotation_mode = 'QUATERNION'

    # ---- right hand, smoking
    s, sd = '.R', -1
    aim(rig, 'lowerarm01' + s, 'wrist' + s, -up * .62 + fwd * .75 + left * sd * .1)   # forearm forward, relaxed
    rotate(rig, 'wrist' + s, fwd, math.radians(-12 * sd))
    curl(rig, s, [(14, 18, 10), (18, 22, 12), (40, 50, 30), (48, 55, 30)], thumb=(10, 10))
    across, n, fdir = hand_frame(rig, s)
    # between index and middle finger, at the proximal phalanges; mouth end on the palm side
    gap = (joint(rig, 'finger2-1' + s) + joint(rig, 'finger2-2' + s) + joint(rig, 'finger3-1' + s) + joint(rig, 'finger3-2' + s)) / 4
    wrist_inv = pose_bone_world(rig, 'wrist' + s).inverted()
    tips = {}
    for name in ('cigarette', 'cigar', 'vape'):
        obj, info = props[name]
        zdir = -n + fdir * .25  # lit end out of the back of the hand, slightly towards the fingertips
        origin = gap - zdir.normalized() * info['grip']
        M = place(obj, origin, zdir, across)
        attach(rig, obj, 'wrist' + s, M)
        placed.append(obj)
        tips[name] = empty('tip_' + name, (0, 0, info['tip']), obj)
        coll.objects.link(tips[name]) if tips[name].name not in coll.objects else None
    # the mouth end of the cigarette, in wrist space, plus its direction and the finger direction
    cig, info = props['cigarette']
    Mc = Matrix(cig['rel'])
    mouth_end = Mc.translation.copy()
    zloc = (Mc.to_3x3() @ Vector((0, 0, 1))).normalized()
    floc = (wrist_inv.to_3x3() @ fdir).normalized()
    key_pose(rig, s, 1)
    # at the lips: from the corner of the mouth, out to the side and a little down; fingers up, elbow out and down
    out = left * sd
    target = lips + fwd * .004 + out * .006
    direction = (out * .75 + fwd * .6 - up * .2).normalized()   # from the corner of the mouth, out to the side
    err = reach(rig, s, (mouth_end, zloc, floc), target, direction, up * .8 - out * .35 + fwd * .25, -up * .6 + out * .8)
    print(f'SMOKE reach error {err:.4f}')
    key_pose(rig, s, 25)
    to_track(rig, 'smoke')

    # ---- left hand, drink
    rig.animation_data_create()
    s, sd = '.L', 1
    aim(rig, 'upperarm01' + s, 'lowerarm01' + s, -up + left * sd * .12 + fwd * .12)
    aim(rig, 'lowerarm01' + s, 'wrist' + s, fwd * .85 - up * .35 + left * sd * -.08)
    curl(rig, s, [(38, 45, 25), (40, 48, 25), (42, 50, 25), (45, 50, 25)], thumb=(25, 20))
    across, n, fdir = hand_frame(rig, s)
    palm = (joint(rig, 'finger3-1' + s) * .7 + joint(rig, 'wrist' + s) * .3)
    for name in ('beer', 'wine', 'whisky', 'shot'):
        obj, info = props[name]
        center = palm + n * (info['radius'] + .012)
        origin = center - up * info['grip'] + up * .01
        M = place(obj, origin, up, fwd)
        attach(rig, obj, 'wrist' + s, M)
        placed.append(obj)
    key_pose(rig, s, 1)
    # sip: rim of the glass at the lips, glass tilted towards the face
    beer, info = props['beer']
    Mb = Matrix(beer['rel'])
    rim = Mb @ Vector((0, 0, .16))
    rim_n = (Mb.to_3x3() @ Vector((0, 0, 1))).normalized()
    floc = (pose_bone_world(rig, 'wrist' + s).inverted().to_3x3() @ fdir).normalized()
    # rim point closest to the face: move the rim centre back by the radius
    target = lips + fwd * (.006 + info['radius']) - up * .004
    direction = (up * .55 - fwd * .83).normalized()  # glass axis tilted back towards the face
    err = reach(rig, s, (rim, rim_n, floc), target, direction, -left * sd + fwd * .3, -up * .6 + left * sd * .8)
    print(f'DRINK reach error {err:.4f}')
    key_pose(rig, s, 25)
    to_track(rig, 'drink')
    # the rig is back in rest pose: parent the props to the wrists (bone-relative transforms from the hold poses)
    finish_attach(rig, placed)
    for o in placed:
        if o.name not in coll.objects:
            coll.objects.link(o)
        bpy.context.scene.collection.objects.unlink(o) if o.name in bpy.context.scene.collection.objects else None
    for t in tips.values():
        if t.name in bpy.context.scene.collection.objects:
            bpy.context.scene.collection.objects.unlink(t)
    mouth = empty('mouth', lips, None)
    mouth.parent = rig
    mouth.parent_type = 'BONE'
    mouth.parent_bone = 'head'
    bpy.context.view_layer.update()
    mouth.matrix_world = Matrix.Translation(lips + fwd * .01)
    coll.objects.link(mouth)
    bpy.context.scene.collection.objects.unlink(mouth)
    for name in ('anchor_head',):
        e = empty(name, joint(rig, 'head', tail=True), None)
        e.parent, e.parent_type, e.parent_bone = rig, 'BONE', 'head'
        bpy.context.view_layer.update()
        e.matrix_world = Matrix.Translation(joint(rig, 'head', tail=True))
        coll.objects.link(e)
        bpy.context.scene.collection.objects.unlink(e)


